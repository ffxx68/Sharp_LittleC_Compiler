; Append printable ASCII to one 24-character line; return -1 when full
; or for control/non-ASCII bytes. State starts empty when the binary is loaded.
; R+2 holds the high byte; R+3 holds the character below the return address.
putchar:
	LDR
	ADIA	3
	STP
	LDM
	CPIA	32
	JPC	PC1403_PUTCHAR_ERROR
	CPIA	127
	JPNC	PC1403_PUTCHAR_ERROR
	LIDP	PC1403_STDOUT_LENGTH
	LDD
	CPIA	24
	JPNC	PC1403_PUTCHAR_ERROR
	EXAB
	LIDP	PC1403_STDOUT_BUFFER
	LP	0x10
	LII	24
	MVWD
	LDR
	ADIA	3
	STP
	LDM
	EXAB
	ADIA	0x10
	STP
	EXAB
	EXAM
	INCP
	LIA	13
	EXAM
	LIDP	PC1403_STDOUT_LENGTH
	LDD
	INCA
	STD
	LP	0x10
	LIDP	PC1403_STDOUT_BUFFER
	LII	24
	EXWD
	LP	0x10
	LIDP	PC1403_STDOUT_BUFFER
	LII	24
	MVWD
	LIJ	1
	LIDP	0x3C00
	LDD
	PUSH
	LIA	9
	STD
	CALL	0x4587
	POP
	LIDP	0x3C00
	STD
	LDR
	ADIA	3
	STP
	LDM
	LIB	0
	RTN
PC1403_PUTCHAR_ERROR:
	LIA	255
	LIB	255
	RTN

PC1403_STDOUT_LENGTH:
	.DB	0
PC1403_STDOUT_BUFFER:
	.DB	32,32,32,32,32,32,32,32,32,32,32,32
	.DB	32,32,32,32,32,32,32,32,32,32,32,32,13
