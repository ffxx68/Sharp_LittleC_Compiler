; Blocking raw PC-1403 key input. Return a zero-extended key code.
key_wait:
	LIDP	PC1403_KEY_SAVED_IRAM
	LP	8
	LII	87
	EXWD
	CALL	0x1494
	LIDP	0xFF5E
	LDD
	LIDP	PC1403_KEY_RESULT
	STD
	LIDP	PC1403_KEY_SAVED_IRAM
	LP	8
	LII	87
	MVWD
	LIDP	PC1403_KEY_RESULT
	LDD
	LIB	0
	RTN

