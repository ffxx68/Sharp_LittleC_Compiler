; Clear/fill the PC-1403 pixel area. Mode 0 clears, mode 1 fills.
lcd_cls:
	LDR
	ADIA	2
	STP
	LDM
	LIDP	PC1403_LCD_CLS_MODE
	STD
	LIDP	PC1403_LCD_SAVED_IRAM
	LP	8
	LII	87
	EXWD
	LIDP	PC1403_LCD_CLS_MODE
	LDD
	CPIA	1
	JRZP	PC1403_LCD_CLS_FILL
	CPIA	0
	JRNZP	PC1403_LCD_CLS_DONE
	LIA	0
	JP	PC1403_LCD_CLS_PAINT
PC1403_LCD_CLS_FILL:
	LIA	0x7F
PC1403_LCD_CLS_PAINT:
	LIDP	12288
	LII	29
	FILD
	LIDP	12333
	LII	14
	FILD
	LIDP	12318
	LII	14
	FILD
	LIDP	12382
	LII	14
	FILD
	LIDP	12397
	LII	14
	FILD
	LIDP	12352
	LII	29
	FILD
PC1403_LCD_CLS_DONE:
	LIDP	PC1403_LCD_SAVED_IRAM
	LP	8
	LII	87
	MVWD
	RTN

PC1403_LCD_CLS_MODE:
	.DB	0
