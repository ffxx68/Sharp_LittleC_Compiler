; Map logical coordinates to the PC-1350 LCD's five 30-column banks.
; The display memory stores each 8-pixel row from top to bottom, so y=0
; selects the last row and the highest bit within that row.
PC1350_LCD_PSET_IMPL:
	LIDP	PC1350_LCD_PSET_X
	LDD
	CPIA	150
	JRNCP	PC1350_LCD_PSET_RETURN
	LIDP	PC1350_LCD_PSET_Y
	LDD
	CPIA	32
	JRNCP	PC1350_LCD_PSET_RETURN
	LIDP	PC1350_LCD_PSET_MODE
	LDD
	CPIA	0
	JRZP	PC1350_LCD_PSET_MODE_OK
	CPIA	1
	JRNZP	PC1350_LCD_PSET_RETURN

