; VAL appends a carriage return, so leave one of the 80 buffer bytes free.
pc1350_val:
	LDR
	ADIA	2
	STP
	LDM
	LIDP	PC1350_ROM_NUMBER_HIGH
	STD
	LDR
	ADIA	3
	STP
	LDM
	LIDP	PC1350_ROM_NUMBER
	STD
	LDR
	ADIA	4
	STP
	LDM
	LIDP	PC1350_ROM_LEFT_LENGTH
	STD
	LIDP	PC1350_ROM_SAVED_IRAM
	LP	8
	LII	87
	EXWD
	LIDP	PC1350_ROM_SAVED_IRAM
	LP	8
	LII	87
	MVWD
	CALL	PC1350_ROM_BEGIN
	JPC	PC1350_ROM_DONE
	CALL	PC1350_ROM_NUMBER_ADDRESS
	JPC	PC1350_ROM_INVALID
	LIDP	PC1350_ROM_LEFT_LENGTH
	LDD
	CPIA	0
	JPZ	PC1350_ROM_INVALID
	CPIA	80
	JPNC	PC1350_ROM_INVALID
	CALL	PC1350_ROM_CHECK_TEXT
	JPC	PC1350_ROM_INVALID
	CALL	PC1350_ROM_DESCRIPTORS
	LIA	1
	LIDP	PC1350_ROM_OPERATION
	STD
	CALL	PC1350_ROM_CALL
	JPC	PC1350_ROM_CONVERSION_FAILED
	CALL	PC1350_ROM_NUMBER_ADDRESS
	LP	16
	LII	7
	EXWD
	LIA	0
	LIB	0
	JP	PC1350_ROM_RETURN
PC1350_ROM_CONVERSION_FAILED:
	LIA	0xFD
	JP	PC1350_ROM_ERROR
