; STR$: caller supplies a valid 8-byte ROM BCD number.
pc1350_str:
	LDR
	ADIA	2
	STP
	LDM
	LIDP	PC1350_ROM_NUMBER_HIGH
	STD
	LDR
	ADIA	3
	STP
	LDM
	LIDP	PC1350_ROM_NUMBER
	STD
	LIDP	PC1350_ROM_SAVED_IRAM
	LP	8
	LII	87
	EXWD
	LIDP	PC1350_ROM_SAVED_IRAM
	LP	8
	LII	87
	MVWD
	CALL	PC1350_ROM_BEGIN
	JPC	PC1350_ROM_DONE
	CALL	PC1350_ROM_NUMBER_ADDRESS
	JPC	PC1350_ROM_INVALID
	LP	16
	LII	7
	MVWD
	LIA	0
	LIDP	PC1350_ROM_OPERATION
	STD
	CALL	PC1350_ROM_CALL
	LP	23
	LDM
	LIB	0
	JP	PC1350_ROM_RETURN
